#!/usr/bin/env python3
"""Render a service's .env from Doppler, or prove a render would change nothing.

Vendored byte-for-byte from spencer0124/skkuverse conventions/render_env.py
(contract conventions.render-env). Edit the producer, never a copy.

The rendered file is a build artifact: the GENERATED header carries a hash of
the body, and a later render refuses to overwrite a file whose body no longer
matches it, so a hand edit cannot be silently lost. The fix for a wrong value
is to change it in Doppler and redeploy.

Secret values never reach argv, stdout or stderr. Errors name keys only.

    render_env.py --keys config/env.prd.keys --out .env --token-file FILE
    render_env.py --keys config/env.dev.keys --out .env --local -p backend -c dev_server
    render_env.py --keys config/env.prd.keys --compare --compose docker-compose.yml \\
        --token-file FILE

Exit codes: 0 success, 1 a check failed (nothing written), 2 usage error.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HEADER_PREFIX = "# GENERATED by render_env.py from Doppler "
HASH_PREFIX = "# body-sha256="
NAME_RE = re.compile(r"^[A-Z_][A-Z0-9_]*$")
DOPPLER_META = ("DOPPLER_PROJECT", "DOPPLER_CONFIG", "DOPPLER_ENVIRONMENT")
FORBIDDEN_CHARS = ("'", "\r", "\n")


class RenderError(Exception):
    """A check failed. The message must never contain a secret value."""


def read_allowlist(path: Path) -> list[str]:
    names: list[str] = []
    for lineno, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        if not NAME_RE.match(line):
            raise RenderError(f"{path}:{lineno}: not a valid variable name: {line!r}")
        if line in names:
            raise RenderError(f"{path}:{lineno}: duplicate name {line}")
        names.append(line)
    if not names:
        raise RenderError(f"{path}: the allowlist is empty")
    return names


def read_token(path: Path) -> str:
    st = path.stat()
    if st.st_uid != os.getuid():
        raise RenderError(f"{path}: token file must be owned by the deploying user")
    if st.st_mode & 0o077:
        raise RenderError(f"{path}: token file must not be readable by group or others (chmod 600)")
    token = path.read_text(encoding="utf-8").strip()
    if not token:
        raise RenderError(f"{path}: token file is empty")
    return token


def fetch(args: argparse.Namespace) -> tuple[str, dict[str, str]]:
    """Download one config as JSON. Returns ("project/config", secrets)."""
    cmd = ["doppler", "secrets", "download", "--no-file", "--format", "json", "--no-fallback"]
    env = dict(os.environ)
    env["DOPPLER_ENABLE_VERSION_CHECK"] = "false"
    if args.token_file:
        # A service token is bound to exactly one config, so no -p/-c here.
        env["DOPPLER_TOKEN"] = read_token(Path(args.token_file))
    else:
        cmd += ["--project", args.project, "--config", args.config]
    try:
        proc = subprocess.run(cmd, env=env, capture_output=True, check=False)
    except FileNotFoundError:
        raise RenderError("the doppler CLI is not installed") from None
    if proc.returncode != 0:
        # Doppler's own errors name the problem (bad token, unknown config),
        # never a value, and the stdout that might hold values is dropped.
        detail = proc.stderr.decode("utf-8", "replace").strip()
        raise RenderError(f"doppler secrets download failed (exit {proc.returncode}): {detail}")
    try:
        data = json.loads(proc.stdout)
    except ValueError:
        raise RenderError("doppler returned something that is not JSON") from None
    if not isinstance(data, dict):
        raise RenderError("doppler returned JSON that is not an object")
    source = f"{data.get('DOPPLER_PROJECT', '?')}/{data.get('DOPPLER_CONFIG', '?')}"
    for meta in DOPPLER_META:
        data.pop(meta, None)
    return source, data


def validate(secrets: dict[str, object], allowlist: list[str]) -> None:
    missing = [n for n in allowlist if n not in secrets]
    unexpected = sorted(n for n in secrets if n not in allowlist)
    problems = []
    if missing:
        problems.append("missing in Doppler: " + ", ".join(missing))
    if unexpected:
        problems.append("in Doppler but not in the allowlist: " + ", ".join(unexpected))
    for name in allowlist:
        value = secrets.get(name)
        if name in missing:
            continue
        if not isinstance(value, str) or value == "":
            problems.append(f"{name}: empty value")
        elif any(ch in value for ch in FORBIDDEN_CHARS):
            problems.append(f"{name}: value contains a single quote or a line break, "
                            "which the .env format here cannot carry")
    if problems:
        raise RenderError("; ".join(problems))


def body_of(secrets: dict[str, str], allowlist: list[str]) -> str:
    # Single quotes are literal in docker compose env_file, Node dotenv and
    # python-dotenv alike: no $ interpolation, no escape processing.
    return "".join(f"{name}='{secrets[name]}'\n" for name in allowlist)


def sha256(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def render_text(source: str, body: str) -> str:
    header = (f"{HEADER_PREFIX}{source}. DO NOT EDIT: change the value in Doppler and redeploy.\n"
              f"{HASH_PREFIX}{sha256(body)}\n")
    return header + body


def check_not_hand_edited(out: Path) -> None:
    """Refuse to replace a rendered file whose body was edited after rendering."""
    if not out.exists():
        return
    lines = out.read_text(encoding="utf-8").splitlines(keepends=True)
    if not lines or not lines[0].startswith(HEADER_PREFIX):
        return  # A pre-migration file, written by hand on purpose.
    if len(lines) < 2 or not lines[1].startswith(HASH_PREFIX):
        raise RenderError(f"{out}: GENERATED header is damaged; inspect it, then rerun with --force")
    recorded = lines[1][len(HASH_PREFIX):].strip()
    if sha256("".join(lines[2:])) != recorded:
        raise RenderError(f"{out} was edited by hand after it was rendered. Move the change into "
                          "Doppler, then rerun with --force to discard the local edit")


def write_atomically(out: Path, text: str) -> None:
    nxt = out.with_name(out.name + ".next")
    prev = out.with_name(out.name + ".prev")
    if nxt.exists():
        nxt.unlink()
    fd = os.open(nxt, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write(text)
            fh.flush()
            os.fsync(fh.fileno())
    except BaseException:
        nxt.unlink(missing_ok=True)
        raise
    if out.exists():
        if prev.exists():
            prev.unlink()
        shutil.copy2(out, prev)
        os.chmod(prev, 0o600)
    os.replace(nxt, out)
    os.chmod(out, 0o600)


def compose_env(compose: Path, project_dir: Path | None) -> dict[str, dict[str, str]]:
    cmd = ["docker", "compose"]
    if project_dir is not None:
        cmd += ["--project-directory", str(project_dir)]
    cmd += ["-f", str(compose), "config", "--format", "json"]
    # stderr is discarded on purpose: compose warns about unset variables by
    # echoing the text after a `$`, which can be part of a secret.
    proc = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, check=False)
    which = "candidate" if project_dir is not None else "live"
    if proc.returncode != 0:
        raise RenderError(f"docker compose config failed for the {which} env "
                          "(stderr suppressed because it can echo values)")
    services = json.loads(proc.stdout).get("services", {})
    return {name: dict(svc.get("environment") or {}) for name, svc in services.items()}


def compare(compose: Path, text: str) -> int:
    """Print KEY same|changed|new|dropped per key; exit 1 on changed or new."""
    compose = compose.resolve()
    tmp = Path(tempfile.mkdtemp(prefix="render-env-"))
    try:
        os.chmod(tmp, 0o700)
        (tmp / ".env").write_text(text, encoding="utf-8")
        os.chmod(tmp / ".env", 0o600)
        live = compose_env(compose, None)
        cand = compose_env(compose, tmp)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)

    def digest(v: object) -> str:
        return hashlib.sha256(str(v).encode("utf-8")).hexdigest()

    status: dict[str, set[str]] = {}
    for svc in sorted(set(live) | set(cand)):
        a, b = live.get(svc, {}), cand.get(svc, {})
        for key in set(a) | set(b):
            if key in a and key not in b:
                st = "dropped"
            elif key in b and key not in a:
                st = "new"
            elif digest(a[key]) != digest(b[key]):
                st = "changed"
            else:
                st = "same"
            status.setdefault(key, set()).add(st)
    bad = 0
    for key in sorted(status):
        states = status[key]
        label = "changed" if "changed" in states else "new" if "new" in states else \
            "dropped" if "dropped" in states else "same"
        if label in ("changed", "new"):
            bad += 1
        print(f"{key} {label}")
    print(f"render_env: compare found {bad} key(s) that would change", file=sys.stderr)
    return 1 if bad else 0


def parse_args(argv: list[str]) -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n", 1)[0])
    p.add_argument("--keys", required=True, help="allowlist of variable names, one per line")
    p.add_argument("--out", help="the .env file to write")
    src = p.add_mutually_exclusive_group(required=True)
    src.add_argument("--token-file", help="file holding a read-only Doppler service token")
    src.add_argument("--local", action="store_true", help="use the personal `doppler login` session")
    p.add_argument("-p", "--project", help="Doppler project (with --local)")
    p.add_argument("-c", "--config", help="Doppler config (with --local)")
    p.add_argument("--compare", action="store_true",
                   help="render to a temp dir and diff what compose would pass; write nothing")
    p.add_argument("--compose", help="compose file (with --compare)")
    p.add_argument("--force", action="store_true", help="overwrite a hand-edited rendered file")
    args = p.parse_args(argv)
    if args.local and not (args.project and args.config):
        p.error("--local needs --project and --config")
    if not args.local and (args.project or args.config):
        p.error("--project/--config only apply with --local; a service token picks its own config")
    if args.compare and not args.compose:
        p.error("--compare needs --compose")
    if not args.compare and not args.out:
        p.error("--out is required unless --compare is given")
    return args


def main(argv: list[str]) -> int:
    os.umask(0o077)
    args = parse_args(argv)
    try:
        allowlist = read_allowlist(Path(args.keys))
        source, secrets = fetch(args)
        validate(secrets, allowlist)
        text = render_text(source, body_of(secrets, allowlist))
        if args.compare:
            return compare(Path(args.compose), text)
        out = Path(args.out)
        if not args.force:
            check_not_hand_edited(out)
        write_atomically(out, text)
    except RenderError as exc:
        print(f"render_env: {exc}", file=sys.stderr)
        return 1
    print(f"render_env: wrote {len(allowlist)} keys from {source} to {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
